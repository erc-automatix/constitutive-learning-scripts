# %% [markdown]
# # Parameter-level hybridization: a hypernetwork for temperature-dependent viscoelasticity
#
# This notebook illustrates hybridization at the level of the material parameters. Each
# coefficient of a constitutive model becomes a module of an external variable, here the
# temperature $T$, and a wrapper extends the signature of the model from $\boldsymbol\varepsilon$ to
# $(\boldsymbol\varepsilon, T)$. At each step, the wrapper evaluates the parameter modules at the
# current temperature and passes the resulting parameters to the unchanged model. When the
# parameter modules are networks, they form a **hypernetwork**, that is a network that generates
# the parameters of another model (Ha, Dai and Le, 2017), here a physics-based constitutive model.
#
# The model is a generalized Maxwell model, whose parameters are the Prony series
# $(E_\infty, E_i, \tau_i)_{i=1..N}$. Four models of its temperature dependence are compared:
#
# - **Arrhenius** and **WLF**: time-temperature superposition, in which all relaxation times are
#   multiplied by a single shift factor, $\tau_i(T) = \tau_i^\text{ref}\,a_T(T)$, given by a
#   classical law, the moduli being constant;
# - **hypernetwork**: the Prony series is generated by networks of the temperature, with one shift
#   factor per branch and a structure that keeps the generated relaxation times physically
#   admissible;
# - **free hypernetwork**: the Prony series is generated by networks of the temperature, with
#   positivity as the only constraint.
#
# The data is generated by a thermorheologically complex material, for which no single shift
# factor exists, and whose moduli also depend on the temperature. The setting is small strain, and
# thermal strains are not considered.

