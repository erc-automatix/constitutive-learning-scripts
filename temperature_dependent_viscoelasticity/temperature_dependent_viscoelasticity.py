# ## Discussion
#
# The values printed above are reported and discussed in the accompanying paper (section
# "Parameter-level hybridization: a hypernetwork for thermoviscoelasticity").
#
# The four models differ only in the modules placed in the coefficient fields of an unchanged
# generalized Maxwell model. The `TemperatureDependent` wrapper extends its signature to
# $(\boldsymbol\varepsilon, T)$ and evaluates these modules at the current temperature at each
# step, the integration of the viscous strains over a step being that of the isothermal model.
# With networks in these fields, the parameter modules form a hypernetwork that generates the whole
# Prony series from the temperature. Calibration goes through the wrapper, the parameter modules
# and the Maxwell update with the same automatic differentiation as for constant parameters.
#
# A single shift factor with constant moduli cannot represent the reference material. The
# Arrhenius and WLF models fit the training tests only approximately, and their errors increase on
# the held-out tests; the calibrated shift laws are compromises between the two mechanisms of the
# reference. The hypernetwork reproduces the training tests and the held-out tests, in
# interpolation at 310 K and in extrapolation at 280 and 330 K. The relaxation times it generates
# recover the two shift laws of the reference, and the moduli it generates recover the entropic
# increase of $E_\infty$ and the decrease of the branch moduli.
#
# The free hypernetwork fits the training tests equally well, but interpolates and extrapolates
# poorly: with three training temperatures, parameters generated without constraint are not
# determined away from the data. The structured hypernetwork generates relaxation times that
# decrease with the temperature, with log-convex shift factors equal to one at $T_\text{ref}$,
# properties shared by the Arrhenius and WLF laws, while leaving each branch its own law. These
# constraints hold by construction on the generated quantities, with fewer parameters than the free
# hypernetwork.
#
# Outside the training range, the temperature laws are no longer constrained by the data. The
# Arrhenius and WLF models overestimate the modulus at low temperature, their single shift law
# slowing down the fast branches too much. The free hypernetwork drifts away from the reference on
# both sides of the training range. The structured hypernetwork remains close to the reference over
# the whole sweep: monotone, log-convex shift factors extrapolate in the same way as the physical
# laws they generalize.
